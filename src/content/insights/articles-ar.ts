/** Mirrors `getRelatedArticles` in the English content file exactly — self-exclusion, 4-item cap, fail-safe empty-array default. */
export function getRelatedArticlesAr(article: InsightArticleAr): InsightArticleAr[] {
  if (!article.relatedArticleSlugs) return [];
  return article.relatedArticleSlugs
    .map((slug) => getInsightArticleAr(slug))
    .filter((related): related is InsightArticleAr => related !== undefined && related.slug !== article.slug)
    .slice(0, 4);
}
